const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const moduleFrom = (file) => import('data:text/javascript;base64,' + Buffer.from(fs.readFileSync(path.join(root, file), 'utf8')).toString('base64'));
(async () => {
 const { vaultCategory, latestVaultFirst } = await moduleFrom('lib/vaultBrowse.js');
 assert.equal(vaultCategory({ category:'tamil-movie', language:'en' }), 'tamil-dubbed-movie');
 assert.equal(vaultCategory({ category:'tamil-series', language:'en', isSeries:true }), 'tamil-dubbed-series');
 assert.equal(vaultCategory({ category:'tamil-movie', language:'ta' }), 'tamil-movie');
 assert.equal(vaultCategory({ category:'tamil-movie', language:'' }), 'tamil-movie');
 assert.equal(vaultCategory({}), 'unclassified');
 assert.equal([{id:1,updatedAt:'2025-01-01'},{id:2,updatedAt:'2026-01-01'}].sort(latestVaultFirst)[0].id,2);
 const { lyricIdentity, chooseLyricMatch } = await moduleFrom('lib/lyricsMatch.js');
 const wanted = {title:'Namaste (From "DC")',artist:'Anirudh Ravichander',album:'DC',duration:150};
 const exact = {id:1,trackName:'Namaste',artistName:'Anirudh Ravichander',albumName:'DC (Original Motion Picture Soundtrack)',duration:150,plainLyrics:'fixture',syncedLyrics:'[00:00]fixture'};
 assert(lyricIdentity(exact,wanted).ok);
 assert(!lyricIdentity({...exact,duration:117},wanted).ok);
 assert(!lyricIdentity({...exact,albumName:'Other film'},wanted).ok);
 assert(!lyricIdentity({...exact,artistName:'Other singer',albumName:''},wanted).ok);
 assert(!lyricIdentity({...exact,trackName:'Namaste remix'},wanted).ok);
 assert(!lyricIdentity({...exact,duration:0,albumName:''},wanted).ok);
 assert.equal(chooseLyricMatch([{...exact,id:2,duration:269},exact],wanted).id,1);
 assert(lyricIdentity({...exact,trackName:"Ain't Nobody"},{...wanted,title:'Aint Nobody'}).ok);
 const source = fs.readFileSync(path.join(root,'app/api/music/lyrics/route.js'),'utf8');
 assert(!source.includes('best.score >= 55'));
 assert(!source.includes('data?.copyright_text'));
 console.log('PASS: 16 classification, matching, ordering and source invariants');
})().catch(e=>{console.error(e);process.exitCode=1});
