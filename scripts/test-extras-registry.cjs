const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const text = fs.readFileSync('lib/extrasRegistry.js','utf8');
  const { extraUrl, validateExtra, legacyExtras, changeExtras } = await import('data:text/javascript;base64,'+Buffer.from(text).toString('base64'));
  const good = { label:'Website',url:'https://public.example/',description:'Test',coverUrl:'',theme:'amber',enabled:true,allowPopups:false };
  for (const url of ['javascript:alert(1)','http://example.com','https://localhost/','https://127.0.0.1/','https://192.168.1.1/','https://user:pass@example.com/','https://[::1]/']) assert.throws(()=>extraUrl(url));
  assert.throws(()=>extraUrl('https://myapp.example/','https://myapp.example/'));
  assert.throws(()=>validateExtra({...good,enabled:'false'}));
  let registry = {version:0,sites:legacyExtras([{id:'old',label:'Legacy',url:'https://legacy.example/'}])};
  assert.equal(registry.sites[0].legacyId,'old');
  registry = changeExtras(registry,'add',{version:0,position:0,site:good},'new');
  assert.equal(registry.sites[0].id,'new');
  assert.throws(()=>changeExtras(registry,'add',{version:0,position:0,site:good},'bad'),e=>e.status===409);
  assert.throws(()=>changeExtras(registry,'add',{version:1,position:0,site:good},'duplicate'));
  registry = changeExtras(registry,'edit',{version:1,id:'new',position:1,site:{...good,enabled:false}},'');
  assert.equal(registry.sites[1].enabled,false);
  registry = changeExtras(registry,'reorder',{version:2,ids:registry.sites.map(s=>s.id).reverse()},'');
  assert.equal(registry.sites[0].id,'new');
  assert.throws(()=>changeExtras(registry,'reorder',{version:3,ids:['new','new']},''));
  registry = changeExtras(registry,'remove',{version:3,id:'new'},'');
  const legacyId = registry.sites[0].id;
  const editedLegacy = changeExtras(registry,'edit',{version:4,id:legacyId,position:0,site:{...registry.sites[0],label:'Renamed'}},'');
  assert.equal(editedLegacy.sites[0].legacyId,'old');
  registry = changeExtras(registry,'remove',{version:4,id:legacyId},'');
  assert.equal(registry.sites.length,0);
  assert.equal(registry.version,5);
  console.log('Extras registry validation, legacy IDs, duplicate checks, ordering, empty list and version-conflict tests passed.');
})().catch(e=>{console.error(e);process.exitCode=1});
